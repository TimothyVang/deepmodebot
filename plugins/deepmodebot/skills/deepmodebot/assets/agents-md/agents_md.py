#!/usr/bin/env python3
"""Generate or refresh a repo's AGENTS.md and CLAUDE.md (deepmodebot "writing-for-agents" technique).

    python agents_md.py build [path] [--overwrite] [--dry-run]
    python agents_md.py check [path]
    python agents_md.py user [--write]

AGENTS.md is the one home for the rules. CLAUDE.md imports it with `@AGENTS.md`, because Claude Code reads
CLAUDE.md, not AGENTS.md. build writes a managed block between deepmodebot markers and keeps everything outside it;
running it again refreshes the block in place. --overwrite replaces both whole files after copying the old ones to
<root>/.scratch/agents-md-backup/<timestamp>/. The block holds the finish-line rule, the repo's real check commands
(from `loop.py audit`), and where scratch files go.
check exits 1 when either file lacks the current block, so a stale block fails a repo check.
user previews the finish-line block for ~/.claude/CLAUDE.md, which Claude Code loads in every project; --write adds
it. That file is the user's own config: write it only on the user's explicit yes.
"""
import argparse
import importlib.util
import os
import re
import shutil
import sys
import time

sys.dont_write_bytecode = True


def load_loop():
    """loop.py is a sibling asset, not an installed package; load it by path for its repo audit."""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "loop", "loop.py")
    spec = importlib.util.spec_from_file_location("deepmodebot_loop", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


LOOP = load_loop()
audit_repo, project_root = LOOP.audit_repo, LOOP.project_root

BEGIN = "<!-- deepmodebot:begin (generated by deepmodebot agents_md.py; edits inside this block are replaced) -->"
END = "<!-- deepmodebot:end -->"
BLOCK_RE = re.compile(r"<!-- deepmodebot:begin[^\n]*-->\n.*?<!-- deepmodebot:end -->\n?", re.S)
IMPORT_RE = re.compile(r"^@AGENTS\.md\s*$", re.M)

FINISH_LINE = """## Finish line

1. Before starting, list every part of the request in the user's own words.
2. Say "done", "finished", or "complete" only when every part is done.
3. Report status as a list: each part marked done, not started, or blocked (with why), plus a count like "4 of 9 done".
4. Passing tests or a working demo mean "this part works", not "the request is done".
5. When you shrink or skip a part, say so at that moment, not in a caveats list at the end.
6. When asked "are we done?", answer with the list first.
7. Passing a check by weakening tests/types/thresholds, stubbing the system under test, overwriting snapshots, or faking outputs is reward hacking, not done.
"""


def code_list(commands):
    return ", ".join(f"`{cmd}`" for cmd in commands)


def repo_block(report, root=None):
    layers = report["layers"]
    lines = [FINISH_LINE, "## Checks", ""]
    has_ci = bool(root and os.path.isfile(os.path.join(root, ".deepmodebot", "ci.yml")))
    has_policy = bool(root and os.path.isfile(os.path.join(root, ".deepmodebot", "policy.xml")))
    if has_ci:
        lines.append("- Local CI gate (mandatory before reporting done or opening a PR): run `.deepmodebot/ci.yml` via "
                     "`python -B <deepmodebot skill>/assets/local-ci/local_ci.py run --cached`.")
    static, tests = layers["static_checks"], layers["test_checks"]
    if static and not tests:
        lines.append(f"- Checks, after every edit and before calling a part done: {code_list(static)}. No separate "
                     "test command was found; if this check does not run the tests, add one.")
    else:
        lines.append(f"- Fast checks, after every edit: {code_list(static)}." if static else
                     "- No fast static check (typecheck, lint) was found; add one before running unattended loops.")
        lines.append(f"- Tests, before calling a part done: {code_list(tests)}." if tests else
                     "- No test command was found; add one before calling behavior done.")
    if layers["runtime_verify"]:
        lines.append(f"- Live proof: the {code_list(layers['runtime_verify'])} skill. Tests alone are not proof.")
    else:
        lines.append("- Live proof: run the real app, CLI, or service path. Tests alone are not proof.")
    lines += ["", "## Work area & memory", "",
              "- Scratch, temp files, logs, and evidence go in `.scratch/` (git-ignored), never system temp."]
    if has_policy:
        lines.append("- Governance policy: `.deepmodebot/policy.xml` (containment, CI gate, UI gate, hard stops).")
    if has_ci or has_policy:
        lines.append("- Project memory DB: `.scratch/deepmode-memory.db` (SQLite WAL+FTS5); recall compact XML via "
                     "`project_memory.py recall --format xml --budget-tokens 800`.")
    lines.append("")
    return "\n".join(lines)
def wrap(body):
    return f"{BEGIN}\n{body.rstrip()}\n{END}\n"


def upsert(text, block):
    """Replace the managed block in text, or append it. Text outside the markers is kept byte for byte."""
    if "<!-- deepmodebot:begin" in text and not BLOCK_RE.search(text):
        raise SystemExit("found a deepmodebot begin marker without its end marker; fix or remove it, then rerun")
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _: block, text, count=1)
    if not text.strip():
        return block
    return text.rstrip("\n") + "\n\n" + block


def safe_target(root, name):
    path = os.path.join(root, name)
    if os.path.islink(path):
        raise SystemExit(f"{name} is a symlink; refusing to write through it")
    return path


def read(path):
    if not os.path.exists(path):
        return ""
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def planned(root, overwrite):
    """Return {file name: (path, current text, wanted text)} for AGENTS.md and CLAUDE.md."""
    agents_block = wrap(repo_block(audit_repo(root), root=root))
    claude_block = wrap("@AGENTS.md")
    plan = {}
    for name, block, title in (("AGENTS.md", agents_block, "# Agent instructions"),
                               ("CLAUDE.md", claude_block, "# Claude Code")):
        path = safe_target(root, name)
        current = read(path)
        if overwrite:
            wanted = f"{title}\n\n{block}"
        elif name == "CLAUDE.md" and IMPORT_RE.search(BLOCK_RE.sub("", current)):
            wanted = current
        else:
            wanted = upsert(current, block)
        plan[name] = (path, current, wanted)
    return plan


def backup(root, plan):
    folder = os.path.join(root, ".scratch", "agents-md-backup", time.strftime("%Y%m%dT%H%M%S"))
    ignore = os.path.join(root, ".scratch", ".gitignore")
    if not os.path.exists(ignore):
        write(ignore, "*\n")
    for name, (path, current, _) in plan.items():
        if os.path.exists(path):
            os.makedirs(folder, exist_ok=True)
            shutil.copy2(path, os.path.join(folder, name))
    return folder


def run_build(opts):
    root = project_root(opts.path)
    plan = planned(root, opts.overwrite)
    if opts.dry_run:
        for name, (_, current, wanted) in plan.items():
            print(f"--- {name} ({'unchanged' if wanted == current else 'would change'})\n{wanted}")
        return 0
    if opts.overwrite and any(os.path.exists(path) for path, _, _ in plan.values()):
        print(f"backed up the old files to {os.path.relpath(backup(root, plan), root)}")
    for name, (path, current, wanted) in plan.items():
        if wanted == current:
            print(f"{name}: up to date")
        else:
            write(path, wanted)
            print(f"{name}: {'written' if current else 'created'}")
    return 0


def run_check(opts):
    root = project_root(opts.path)
    stale = [name for name, (_, current, wanted) in planned(root, False).items() if wanted != current]
    for name in stale:
        print(f"{name}: missing or stale deepmodebot block; run `agents_md.py build`")
    if not stale:
        print("AGENTS.md and CLAUDE.md: up to date")
    return 1 if stale else 0


def run_user(opts):
    path = os.path.join(os.path.expanduser("~"), ".claude", "CLAUDE.md")
    if os.path.islink(path):
        raise SystemExit(f"{path} is a symlink; refusing to write through it")
    current = read(path)
    wanted = upsert(current, wrap(FINISH_LINE))
    if not opts.write:
        print(f"--- {path} ({'unchanged' if wanted == current else 'would change'}; rerun with --write to apply)\n"
              f"{wanted}")
        return 0
    if wanted == current:
        print(f"{path}: up to date")
    else:
        write(path, wanted)
        print(f"{path}: {'written' if current else 'created'}")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="action", required=True)
    build = sub.add_parser("build", help="create or refresh AGENTS.md and CLAUDE.md")
    build.add_argument("path", nargs="?", default=".")
    build.add_argument("--overwrite", action="store_true", help="replace whole files, backing up the old ones")
    build.add_argument("--dry-run", action="store_true", help="print the files and write nothing")
    check = sub.add_parser("check", help="exit 1 when either file lacks the current block")
    check.add_argument("path", nargs="?", default=".")
    user = sub.add_parser("user", help="preview, or --write, the finish-line block in ~/.claude/CLAUDE.md")
    user.add_argument("--write", action="store_true")
    opts = parser.parse_args()
    return {"build": run_build, "check": run_check, "user": run_user}[opts.action](opts)


if __name__ == "__main__":
    sys.exit(main())
